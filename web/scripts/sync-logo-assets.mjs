#!/usr/bin/env node
// Run from the source checkout: npm --prefix web run sync:logo
// SVG paths are the source of truth; no font installation is needed to render.
import { copyFile, mkdir, readFile, readdir, rm, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import path from "node:path";
import { fileURLToPath } from "node:url";
import sharp from "sharp";

const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.resolve(webRoot, "../assets/figs/logo");
const publicRoot = path.join(webRoot, "public");
const targetRoot = path.join(publicRoot, "brand");
const desktopRoot = path.resolve(webRoot, "../apps/desktop/assets");
await mkdir(targetRoot, { recursive: true });
const assets = {};
const dimensions = {};
const versionedNames = new Set();

async function versionedAsset(source, label) {
  const bytes = await readFile(source);
  const hash = createHash("sha256").update(bytes).digest("hex").slice(0, 12);
  const name = `lorevia-${label}-${hash}${path.extname(source)}`;
  await writeFile(path.join(targetRoot, name), bytes);
  versionedNames.add(name);
  return `/brand/${name}`;
}

for (const color of ["color", "black"]) {
  for (const kind of ["logo", "word", "full"]) {
    const name = `${color}-${kind}.png`;
    const source = path.join(sourceRoot, `${color}-${kind}.svg`);
    const width = kind === "logo" ? 512 : kind === "word" ? 1200 : 1600;
    const png = await sharp(source, { density: 384 }).resize({ width }).png().toBuffer();
    await copyFile(source, path.join(targetRoot, `${color}-${kind}.svg`));
    await sharp(png).toFile(path.join(sourceRoot, name));
    const info = await sharp(png).toFile(path.join(targetRoot, name));
    const key = `${color === "black" ? "mono" : ""}${kind === "word" ? "Wordmark" : kind[0].toUpperCase() + kind.slice(1)}`;
    const label = `${color === "black" ? "mono-" : ""}${kind}`;
    const assetKey = key[0].toLowerCase() + key.slice(1);
    assets[assetKey] = await versionedAsset(source, label);
    dimensions[assetKey] = { width: info.width, height: info.height };
    console.log(`${name}: ${info.width} × ${info.height}`);
  }
}

// The desktop shell uses monochrome artwork and inverts it in dark mode.
await copyFile(path.join(targetRoot, "black-logo.png"), path.join(desktopRoot, "mark.png"));
await copyFile(path.join(targetRoot, "black-word.png"), path.join(desktopRoot, "wordmark.png"));

// Keep old URLs useful for images embedded in already-saved notes/documents.
for (const [alias, source] of Object.entries({
  "logo.png": "color-logo.png",
  "logo_black.png": "black-logo.png",
  "banner.png": "color-word.png",
  "logo-ver2.png": "color-logo.png",
})) {
  await copyFile(path.join(targetRoot, source), path.join(publicRoot, alias));
}

for (const [name, size] of [["favicon-16x16.png", 16], ["favicon-32x32.png", 32], ["apple-touch-icon.png", 180]]) {
  await sharp(path.join(sourceRoot, "color-logo.svg"), { density: 384 }).resize(size, size).png().toFile(path.join(targetRoot, name));
  await copyFile(path.join(targetRoot, name), path.join(publicRoot, name));
  assets[size === 16 ? "favicon16" : size === 32 ? "favicon32" : "appleTouchIcon"] = await versionedAsset(path.join(targetRoot, name), name.replace(".png", ""));
}

await writeFile(path.join(webRoot, "lib/brand-assets.generated.ts"),
  `// Generated by npm run sync:logo. Do not edit resource URLs by hand.\nexport const BRAND_ASSETS = ${JSON.stringify(assets, null, 2)} as const;\n\nexport const BRAND_DIMENSIONS = ${JSON.stringify(dimensions, null, 2)} as const;\n`);

// Only remove obsolete versions owned by this generator.
for (const name of await readdir(targetRoot)) {
  if (/^lorevia-.+-[a-f0-9]{12}\.(svg|png)$/.test(name) && !versionedNames.has(name)) {
    await rm(path.join(targetRoot, name));
  }
}
